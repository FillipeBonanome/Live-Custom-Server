local function bestPotion(list, vocId, level)
	local chosen
	for _, potion in ipairs(list) do
		if(potion[2] <= level and (not potion[3] or isInArray(potion[3], vocId))) then
			chosen = potion[1]
		end
	end
	return chosen
end

-- level 200+: every piece is Legendary (4 enchantment slots) and gets enchantments. The weapons get Necrotic (life leech),
-- the necklace and ring get Soulburn (mana leech), so the set always has both leeches (names from data/XML/enchantments.xml)
local RARE_LEVEL = 200
local RARITY = "Legendary"
local NECKLACE_ID, RING_ID = 2130, 2179 -- golden amulet, gold ring
local ENCHANTS = {
	weapon = {"Necrotic", "Deadly"},
	wand = {"Necrotic", "Arcane"},
	head = {"Vitality", "Stoneskin"},
	armor = {"Rejuvenating", "Stoneskin"},
	legs = {"Vitality", "Earthen"},
	feet = {"Clearing", "Vitality"},
	shield = {"Warding", "Stoneskin"},
	necklace = {"Soulburn", "Charm"},
	ring = {"Soulburn", "Charm"}
}

local function giveSet(cid, vocId, level)
	for _, slot in ipairs({CONST_SLOT_HEAD, CONST_SLOT_ARMOR, CONST_SLOT_RIGHT, CONST_SLOT_LEFT, CONST_SLOT_LEGS, CONST_SLOT_FEET, CONST_SLOT_AMMO}) do
		local item = getPlayerSlotItem(cid, slot)
		if(item.uid > 0) then
			doRemoveItem(item.uid)
		end
	end

	local rare = level >= RARE_LEVEL
	if(rare) then
		for _, slot in ipairs({CONST_SLOT_NECKLACE, CONST_SLOT_RING}) do
			local item = getPlayerSlotItem(cid, slot)
			if(item.uid > 0) then
				doRemoveItem(item.uid)
			end
		end
	end

	local names = {}
	-- enchants: list of enchantment names, only used (together with the rarity) from level 200
	local function give(id, count, enchants)
		local itemInfo = getItemInfo(id)
		local label = itemInfo and itemInfo.name or tostring(id)
		if(rare and enchants) then
			local item = doCreateItemEx(id, count or 1)
			if(item and item > 0 and doItemSetRarity(item, RARITY)) then
				local applied = {}
				for _, enchant in ipairs(enchants) do
					if(doItemEnchant(item, enchant)) then
						table.insert(applied, enchant)
					end
				end

				if(doPlayerAddItemEx(cid, item, true) ~= RETURNVALUE_NOERROR) then
					doTileAddItemEx(getCreaturePosition(cid), item)
				end

				table.insert(names, RARITY .. " " .. label .. " [" .. table.concat(applied, ", ") .. "]")
				return
			end
		end

		doPlayerAddItem(cid, id, count or 1)
		table.insert(names, label)
	end

	local vocInfo = getVocationInfo(vocId)
	local base = vocInfo and vocInfo.fromVocation or vocId
	local weapon = pick(WEAPONS[vocId] or {}, level)
	local twoHanded = false
	if(weapon) then
		local weaponEnchants = ENCHANTS.weapon
		if(weapon[4] == "" and isInArray({1, 2, 9}, base)) then
			weaponEnchants = ENCHANTS.wand
		end

		give(weapon[2], 1, weaponEnchants)
		twoHanded = weapon[3] == 1
		if(base == 13) then
			give(weapon[2], 1, weaponEnchants) -- assassin line dual wields
		end
	end

	local set = pick(SETS[vocId] or SETS[0], level)
	if(set) then
		give(set[2], 1, ENCHANTS.head)
		give(set[3], 1, ENCHANTS.armor)
		give(set[4], 1, ENCHANTS.legs)
		give(set[5], 1, ENCHANTS.feet)
		-- two-handed weapons (bows, staffs...) leave no room for a shield, except for the vocations that can two-hand + shield
		if((not twoHanded or base == 15) and base ~= 13) then
			give(set[6], 1, ENCHANTS.shield)
		end
	end

	if(rare) then
		give(NECKLACE_ID, 1, ENCHANTS.necklace)
		give(RING_ID, 1, ENCHANTS.ring)
	end

	if(weapon and weapon[4] ~= "") then
		local ammo = pick(AMMO[weapon[4]], level)
		if(ammo) then
			give(ammo[2], 100)
		end
	end

	for _, kind in ipairs({"health", "mana", "spirit"}) do
		local potion = bestPotion(POTIONS[kind], vocId, level)
		if(potion) then
			give(potion, 100)
		end
	end

	return table.concat(names, ", ") .. "."
end

local COMBAT_SKILLS = {SKILL_FIST, SKILL_CLUB, SKILL_SWORD, SKILL_AXE, SKILL_DISTANCE, SKILL_SHIELD}

function onSay(cid, words, param, channel)
	local name, level = param:match("^(.-)%s+(%d+)%s*$")
	level = tonumber(level)
	if(not name or name == "" or not level or level < 1) then
		doPlayerSendTextMessage(cid, MESSAGE_STATUS_CONSOLE_BLUE, "Usage: !testvoc <vocation name>, <level>   e.g. !testvoc Archer 100")
		return true
	end

	name = name:gsub("[,%s]+$", ""):lower()
	local info
	for id = 0, 60 do
		local v = getVocationInfo(id)
		if(v and v.name:lower() == name) then
			info = v
			break
		end
	end

	if(not info) then
		local names = {}
		for id = 1, 60 do
			local v = getVocationInfo(id)
			if(v and v.name ~= "None") then
				table.insert(names, v.name)
			end
		end
		doPlayerSendTextMessage(cid, MESSAGE_STATUS_CONSOLE_BLUE, "Vocation not found. Available: " .. table.concat(names, ", ") .. ".")
		return true
	end

	local mult = info.skillMultipliers
	local lowest = mult[SKILL__MAGLEVEL]
	for _, skill in ipairs(COMBAT_SKILLS) do
		lowest = math.min(lowest, mult[skill])
	end

	doPlayerSetVocation(cid, info.id)

	local exp = getExperienceForLevel(level)
	local diff = exp - getPlayerExperience(cid)
	if(diff ~= 0) then
		doPlayerAddExperience(cid, diff)
	end

	for _, skill in ipairs(COMBAT_SKILLS) do
		doPlayerSetSkillLevel(cid, skill, math.max(10, math.floor(100 * lowest / mult[skill] + 0.5)))
	end

	local magic = math.max(0, math.floor(100 * lowest / mult[SKILL__MAGLEVEL] + 0.5))
	doPlayerSetMagicLevel(cid, magic)

	local given = giveSet(cid, info.id, level)

	doCreatureAddHealth(cid, getCreatureMaxHealth(cid) - getCreatureHealth(cid))
	doCreatureAddMana(cid, getCreatureMaxMana(cid) - getCreatureMana(cid))

	doPlayerSendTextMessage(cid, MESSAGE_STATUS_CONSOLE_BLUE, "Now " .. info.name .. " level " .. level .. " (magic " .. magic .. ", fist "
		.. getPlayerSkillLevel(cid, SKILL_FIST) .. ", club " .. getPlayerSkillLevel(cid, SKILL_CLUB) .. ", sword "
		.. getPlayerSkillLevel(cid, SKILL_SWORD) .. ", axe " .. getPlayerSkillLevel(cid, SKILL_AXE) .. ", distance "
		.. getPlayerSkillLevel(cid, SKILL_DISTANCE) .. ", shielding " .. getPlayerSkillLevel(cid, SKILL_SHIELD) .. ").")
	return true
end
